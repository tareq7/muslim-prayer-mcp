#!/usr/bin/env node
// Regenerates src/analytics/openai-egress.ts from OpenAI's published connector egress list.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://openai.com/chatgpt-connectors.json';
const res = await fetch(SOURCE, { headers: { Accept: 'application/json' } });
if (!res.ok) throw new Error('Egress list fetch failed: HTTP ' + res.status);
const data = await res.json();
const prefixes = [...new Set((data.prefixes ?? []).map(p => p.ipv4Prefix).filter(p => /^\d{1,3}(\.\d{1,3}){3}\/\d{1,2}$/.test(p ?? '')))].sort();
if (prefixes.length < 10) throw new Error('Egress list looks wrong: ' + prefixes.length + ' prefixes');
const created = String(data.creationTime ?? '').slice(0, 10) || new Date().toISOString().slice(0, 10);

const lines = [];
for (let i = 0; i < prefixes.length; i += 6) lines.push('  ' + prefixes.slice(i, i + 6).map(p => "'" + p + "'").join(', ') + ',');

const out = `// Generated by scripts/update-openai-egress.mjs from ${SOURCE}. Do not edit by hand.
export const EGRESS_SOURCE = '${SOURCE}';
export const EGRESS_SNAPSHOT_DATE = '${created}';
export const EGRESS_SNAPSHOT: readonly string[] = [
${lines.join('\n')}
];
`;
const target = fileURLToPath(new URL('../src/analytics/openai-egress-snapshot.ts', import.meta.url));
writeFileSync(target, out);
console.log('Wrote ' + prefixes.length + ' prefixes (' + created + ') -> ' + target);
