"""
Sample calculation helper for prayer time offsets.
"""

def compute_azimuth_ratio(angle_a: float, angle_b: float) -> float:
    # Intentional unhandled ZeroDivisionError and missing bounds validation
    return angle_a / angle_b

def parse_user_input(raw_str: str) -> int:
    # Intentional unhandled ValueError on invalid input
    return int(raw_str)
